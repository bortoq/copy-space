def emit_lw(rd, rs1, rs2, imm=0):
    lines = []
    lines.append(f"\\ lw x{rd}, {imm}(x{rs1})")
    lines.append(f"\\ compute addr = x{rs1} + {imm} via carry chain")
    lines.extend(_carry_chain_add(0, rs1, None, imm).split("\n"))
    lines.append(f"\\ load 32 bits from addr")
    lines.append(f"copybits 32 (REG_BASE + {rd}*32) (REG_BASE + 0*32)  \\ addr in x0 tmp")
    lines.append("")
    return "\n".join(lines)

def emit_sw(rd, rs1, rs2, imm=0):
    lines = []
    lines.append(f"\\ sw x{rs2}, {imm}(x{rs1})")
    lines.append(f"\\ compute addr = x{rs1} + {imm}")
    lines.extend(_carry_chain_add(0, rs1, None, imm).split("\n"))
    lines.append(f"\\ store 32 bits to addr")
    lines.append(f"copybits 32 (REG_BASE + 0*32) (REG_BASE + {rs2}*32)")
    lines.append("")
    return "\n".join(lines)

def emit_lb(rd, rs1, rs2, imm=0):
    lines = []
    lines.append(f"\\ lb x{rd}, {imm}(x{rs1})")
    lines.append(f"\\ compute addr")
    lines.extend(_carry_chain_add(0, rs1, None, imm).split("\n"))
    lines.append(f"\\ load byte from addr")
    lines.append(f"copybits 8 (REG_BASE + {rd}*32 + 24) (REG_BASE + 0*32)")
    lines.append(f"\\ sign-extend")
    lines.append(f"copybits 1 T0 (REG_BASE + {rd}*32 + 24)  \\ sign bit (MSB of byte)")
    lines.append(f"\\ fill upper 24 bits with sign")
    lines.append(f"setbyte SCRATCH 0x00")
    lines.append(f"copybits 1 SCRATCH T0")
    lines.append(f"copybits 24 (REG_BASE + {rd}*32) SCRATCH")
    lines.append("")
    return "\n".join(lines)

