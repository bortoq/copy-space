#!/usr/bin/env python3
"""
riscv_to_f0.py — эмиттеры .f0 для RV32I инструкций в Copy-Space.
Генерирует валидный .f0 код для каждой RISC-V инструкции,
используя примитивы copybits, ADD24, BAND/BOR/BXOR/BNOT.
"""

REG_BASE = "((524288 - 256) * 8)"  # bitaddr в .f0

def emit_prologue(reg_init):
    """Генерирует .f0 пролог: инициализация 32 регистров в space"""
    lines = []
    lines.append("\\ Generated by riscv_to_f0.py")
    lines.append("const REG_BASE " + REG_BASE)
    lines.append("")
    lines.append("\\ Scratch space for ALU operations")
    lines.append("\\ Temporary scratch space (after register file)")
    lines.append("const SCRATCH (REG_BASE + 1024)")
    lines.append("const TMP_CARRY (SCRATCH + 0)")
    lines.append("\\ Prologue: initialize selected RISC-V registers")
    for i in sorted(reg_init.keys()):
        val = reg_init.get(i, 0)
        byte0 = (val >> 24) & 0xFF
        byte1 = (val >> 16) & 0xFF
        byte2 = (val >> 8) & 0xFF
        byte3 = val & 0xFF
        lines.append(f"setbyte (REG_BASE + {i*32}) 0x{byte0:02x}")
        lines.append(f"setbyte (REG_BASE + {i*32 + 8}) 0x{byte1:02x}")
        lines.append(f"setbyte (REG_BASE + {i*32 + 16}) 0x{byte2:02x}")
        lines.append(f"setbyte (REG_BASE + {i*32 + 24}) 0x{byte3:02x}")
    lines.append("")
    return "\n".join(lines)

def _carry_chain_add(rd, rs1, rs2_reg, imm_val):
    """32-bit add: rd = rs1 + val, где val либо из регистра rs2_reg, либо immediate"""
    lines = []
    is_imm = imm_val is not None
    val_desc = f"imm_{imm_val}" if is_imm else f"x{rs2_reg}"
    
    lines.append(f"\\ 32-bit add: x{rd} = x{rs1} + {val_desc} (via 24+8 carry chain)")
    
    if is_imm:
        # Load immediate as 24-bit value
        imm_lo = imm_val & 0xFFFFFF
        imm_hi = (imm_val >> 24) & 0xFF
        lines.append(f"set24 VAR_B24 0x{imm_lo:06x}")  # low 24 bits
        hi_src = f"0x{imm_hi:02x}"
    else:
        hi_src = f"(REG_BASE + {rs2_reg}*32)"
        lines.append(f"copybits 24 VAR_B24 (REG_BASE + {rs2_reg}*32 + 8)")
    
    # Step 1: low 24 bits
    lines.append(f"copybits 24 VAR_A24 (REG_BASE + {rs1}*32 + 8)")
    lines.append(f"word_ADD24")
    lines.append(f"copybits 24 (REG_BASE + {rd}*32 + 8) VAR_SUM24")
    lines.append(f"copybits 1 T0 VAR_COUT")
    
    # Step 2: high 8 bits + carry
    lines.append(f"\\ hi8 = rs1_hi + val_hi + carry")
    lines.append(f"set24 VAR_A24 0x000000")
    lines.append(f"copybits 8 VAR_A24 (REG_BASE + {rs1}*32)")
    if is_imm:
        lines.append(f"set24 VAR_B24 0x000000")
        lines.append(f"setbyte VAR_B24 {hi_src}")
    else:
        lines.append(f"set24 VAR_B24 0x000000")
        lines.append(f"copybits 8 VAR_B24 ({hi_src})")
    lines.append(f"copybits 1 TMP_CARRY T0  \\ inject carry")
    lines.append(f"copybits 1 (VAR_B24 + 0) TMP_CARRY")
    lines.append(f"word_ADD24")
    lines.append(f"copybits 8 (REG_BASE + {rd}*32) VAR_SUM24")
    lines.append("")
    return "\n".join(lines)


def emit_add(rd, rs1, rs2, imm=0):
    return _carry_chain_add(rd, rs1, rs2, None)

def emit_sub(rd, rs1, rs2, imm=0):
    lines = []
    lines.append(f"\\ sub x{rd}, x{rs1}, x{rs2} = add(x{rs1}, ~x{rs2}, cin=1)")
    # Invert rs2 low 24 bits
    lines.append(f"copybits 24 VAR_A24 (REG_BASE + {rs2}*32 + 8)")
    lines.append(f"word_BNOT")
    lines.append(f"copybits 24 (SCRATCH + 32) VAR_SUM24  \\ ~rs2[23:0]")
    # Set carry-in = 1
    lines.append(f"setbit (SCRATCH + 56) CONST1")
    # Add: rd = rs1 + (~rs2) + 1
    lines.append(f"copybits 24 VAR_A24 (REG_BASE + {rs1}*32 + 8)")
    lines.append(f"copybits 24 VAR_B24 (SCRATCH + 32)")
    lines.append(f"copybits 1 (VAR_B24 + 0) (SCRATCH + 56)")
    lines.append(f"word_ADD24")
    lines.append(f"copybits 24 (REG_BASE + {rd}*32 + 8) VAR_SUM24")
    lines.append(f"copybits 1 T0 VAR_COUT")
    # High 8 bits: invert rs2 hi, add rs1 hi + carry
    lines.append(f"copybits 8 VAR_A24 (REG_BASE + {rs2}*32)")
    lines.append(f"word_BNOT")
    lines.append(f"copybits 8 (SCRATCH + 40) VAR_SUM24")
    lines.append(f"copybits 8 VAR_A24 (REG_BASE + {rs1}*32)")
    lines.append(f"copybits 8 VAR_B24 (SCRATCH + 40)")
    lines.append(f"copybits 1 (VAR_B24 + 0) T0  \\ inject carry from step 1")
    lines.append(f"word_ADD24")
    lines.append(f"copybits 8 (REG_BASE + {rd}*32) VAR_SUM24")
    lines.append("")
    return "\n".join(lines)

def emit_addi(rd, rs1, rs2, imm):
    return _carry_chain_add(rd, rs1, None, imm)

def emit_xor(rd, rs1, rs2, imm=0):
    lines = []
    lines.append(f"\\ xor x{rd}, x{rs1}, x{rs2}")
    for b in range(32):
        lines.append(f"copybits 1 BA (REG_BASE + {rs1}*32 + {b})")
        lines.append(f"copybits 1 BB (REG_BASE + {rs2}*32 + {b})")
        lines.append("word_BXOR")
        lines.append(f"copybits 1 (REG_BASE + {rd}*32 + {b}) BR")
    lines.append("")
    return "\n".join(lines)

