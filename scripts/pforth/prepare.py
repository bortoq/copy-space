"""Build and run 32-bit pForth to generate its built-in target dictionary."""
import argparse
import hashlib
import json
import os
import shlex
import struct
import subprocess
from pathlib import Path

from common import ROOT, PORT, UPSTREAM, REVISION, sources, flags


def prepare(output, additions=(), extra_cflags=(), artifacts=None):
    output = output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    artifacts = artifacts or ROOT / "tmp/pforth-prepare"
    artifacts.mkdir(parents=True, exist_ok=True)
    source = (UPSTREAM / "fth/system.fth").read_bytes()
    marker = b"\\ Auto Initialization"
    if source.count(marker) != 1:
        raise ValueError("pinned system.fth boundary changed")
    source = source[:source.index(marker)]
    for path in additions:
        source += b"\n" + path.read_bytes() + b"\n"
    (artifacts / "system-input.fth").write_bytes(source)
    executable = artifacts / "prepare32"
    command = shlex.split(os.environ.get("CC", "cc")) + [
        "-m32", "-O2", "-std=c99", "-ffreestanding", "-nostdlib", "-fno-pie", "-no-pie",
        "-fno-stack-protector", "-Wall", "-Wextra", "-Werror",
        "-Wl,--build-id=none", "-Wl,-e,_start",
    ] + flags(True) + list(extra_cflags) + [str(path) for path in sources(True)] + ["-o", str(executable)]
    (artifacts / "compile.json").write_text(json.dumps(command, indent=2)+"\n")
    result = subprocess.run(command, capture_output=True)
    (artifacts / "compile.stderr").write_bytes(result.stderr)
    if result.returncode:
        raise ValueError(result.stderr.decode(errors="replace"))
    result = subprocess.run([str(executable)], input=source, capture_output=True, timeout=30)
    (artifacts / "dictionary.bin").write_bytes(result.stdout)
    (artifacts / "prepare.stderr").write_bytes(result.stderr)
    if result.returncode == -31:
        raise ValueError("the execution sandbox blocks i386 system calls; regenerate the dictionary outside it")
    if result.returncode or result.stdout[:4] != b"PFD1":
        raise ValueError(f"32-bit pForth dictionary preparation failed ({result.returncode}): "
                         + result.stdout[:500].decode(errors="replace"))
    names, code, context, primitives = struct.unpack_from("<4I", result.stdout, 4)
    if len(result.stdout) != 20+names+code or not 0 < context < names or not code % 4 == 0:
        raise ValueError("invalid generated dictionary")
    arrays = [("MinDicNames", result.stdout[20:20+names], 32768),
              ("MinDicCode", result.stdout[20+names:], 65536)]
    text = ["/* Generated by scripts/pforth/prepare.py from pinned pForth; do not edit. */",
            "#define IF_LITTLE_ENDIAN 1", "#define PF_PREPARED_CELL_SIZE 4",
            f"#define HEADERPTR {names}", f"#define RELCONTEXT {context}", f"#define CODEPTR {code}",
            f"#define PF_PREPARED_PRIMITIVES {primitives}",
            "typedef char pf_dictionary_cell_match[(PF_CELL_SIZE == PF_PREPARED_CELL_SIZE) ? 1 : -1];",
            "typedef char pf_dictionary_primitive_match[(NUM_PRIMITIVES == PF_PREPARED_PRIMITIVES) ? 1 : -1];"]
    for name, data, extra in arrays:
        text.append(f"static uint8_t {name}[{len(data)+extra}] __attribute__((aligned(16))) = {{")
        for start in range(0, len(data), 16):
            text.append("    "+", ".join(f"0x{v:02x}" for v in data[start:start+16])+",")
        text.append("};")
    rendered = "\n".join(text)+"\n"
    output.write_text(rendered)
    manifest = {"upstream_revision": REVISION, "cell_bytes": 4, "little_endian": True,
                "names_bytes": names, "code_bytes": code, "relative_context": context,
                "primitives": primitives, "headers_reserve_bytes": 32768, "code_reserve_bytes": 65536,
                "system_input_sha256": hashlib.sha256(source).hexdigest(),
                "dictionary_sha256": hashlib.sha256(result.stdout).hexdigest(),
                "header_sha256": hashlib.sha256(rendered.encode()).hexdigest()}
    output.with_name(output.name+".json").write_text(json.dumps(manifest, indent=2)+"\n")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, default=PORT / "pfdicdat.h")
    args = parser.parse_args()
    try:
        manifest = prepare(args.output)
        print(f"pForth dictionary: {manifest['names_bytes']} name bytes, {manifest['code_bytes']} code bytes")
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        parser.exit(1, str(error)+"\n")


if __name__ == "__main__":
    main()
