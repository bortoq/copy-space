def emit_lui(rd, rs1, rs2, imm=0):
    val = imm & 0xFFFFFFFF
    return (
        f"\\ lui x{rd}, 0x{imm:x}\n"
        f"setbyte (REG_BASE + {rd}*32 + 0)  0x{(val >> 24) & 0xFF:02x}\n"
        f"setbyte (REG_BASE + {rd}*32 + 8)  0x{(val >> 16) & 0xFF:02x}\n"
        f"setbyte (REG_BASE + {rd}*32 + 16) 0x{(val >> 8) & 0xFF:02x}\n"
        f"setbyte (REG_BASE + {rd}*32 + 24) 0x{val & 0xFF:02x}\n\n"
    )

def emit_auipc(rd, rs1, rs2, imm=0):
    return f"\\ auipc x{rd}, 0x{imm:x} (resolved in trace)\n"

def emit_jal(rd, rs1, rs2, imm=0):
    return f"\\ jal x{rd}, 0x{imm:x} (resolved in trace)\n"

def emit_jalr(rd, rs1, rs2, imm=0):
    return f"\\ jalr x{rd}, x{rs1}, 0x{imm:x} (resolved in trace)\n"

def emit_epilogue(out_regs, dump_all_regs=False):
    lines = []
    lines.append("\\ Epilogue: copy output regs to TESTG")
    if dump_all_regs:
        for reg in range(32):
            lines.append(f"copybits 32 (TESTG + {reg*32}) (REG_BASE + {reg}*32)")
    else:
        for i, reg in enumerate(out_regs):
            lines.append(f"copybits 8 (TESTG + {i*8}) (REG_BASE + {reg}*32 + 24)")
    lines.append("HALT")
    return "\n".join(lines)

def instruction_to_f0(instr_name, rd=0, rs1=0, rs2=0, imm=0):
    dispatch = {
        "add": emit_add, "sub": emit_sub, "addi": emit_addi,
        "xor": emit_xor, "or": emit_or, "and": emit_and,
        "andi": emit_andi, "ori": emit_ori, "xori": emit_xori,
        "sll": emit_sll, "srl": emit_srl, "sra": emit_sra,
        "slli": emit_slli, "srli": emit_srli, "srai": emit_srai,
        "slt": emit_slt, "sltu": emit_sltu,
        "slti": emit_slti, "sltiu": emit_sltiu,
        "lw": emit_lw, "sw": emit_sw, "lb": emit_lb,
        "lbu": emit_lbu, "lh": emit_lh, "lhu": emit_lhu,
        "sb": emit_sb, "sh": emit_sh,
        "beq": emit_beq, "bne": emit_bne, "blt": emit_blt, "bge": emit_bge, "bltu": emit_bltu, "bgeu": emit_bgeu,
        "lui": emit_lui, "auipc": emit_auipc, "jal": emit_jal, "jalr": emit_jalr,
    }
    fn = dispatch.get(instr_name)
    if fn is None:
        return f"\\ UNSUPPORTED: {instr_name} x{rd}, x{rs1}, x{rs2}, imm=0x{imm:x}\n"
    return fn(rd, rs1, rs2, imm)


